window.CURRENT_LANG = 'en';
window.t = function (key) {
  const dict = I18N[window.CURRENT_LANG] || {};
  return dict[key] || (I18N.en && I18N.en[key]) || key;
};
window.applyI18n = function (lang) {
  window.CURRENT_LANG = lang || 'en';
  const tr = window.t;
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const v = tr(el.getAttribute('data-i18n'));
    if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    const v = tr(el.getAttribute('data-i18n-placeholder'));
    if (v) el.setAttribute('placeholder', v);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    const v = tr(el.getAttribute('data-i18n-aria'));
    if (v) el.setAttribute('aria-label', v);
  });
  const code = window.CURRENT_LANG === 'hi-en' ? 'hi' : window.CURRENT_LANG;
  document.documentElement.lang = code === 'auto' ? 'en' : code;
};
